# ══════════════════════════════════════════════════════════════════════
#  ④ VERIFY_SPECS — 진위확인 번호
# ══════════════════════════════════════════════════════════════════════
#
#  발급처마다 형식이 완전히 다릅니다. 실물에서 확인된 것들:
#
#      정부24          1734-5821-9043-2216   (4-4-4-4)
#      certpia(대학)   3626106221013994      (16자리, 하이픈 없음)
#      대학 문서번호    제 2023-0046124 호
#
#  ┌─ 수정 방법 ────────────────────────────────────────────────────┐
#  │  새 형식을 발견하면 아래에 한 줄 추가합니다.                     │
#  │  정규식에서 괄호 ( ) 안이 실제로 뽑을 값입니다.                  │
#  │                                                                │
#  │      Verify("병원 발급번호",                                    │
#  │             re.compile(r"발급번호\s*[:：]\s*([A-Z0-9-]{8,})"),  │
#  │             "병원 홈페이지에서 조회"),                          │
#  └────────────────────────────────────────────────────────────────┘

@dataclass(frozen=True)
class Verify:
    name: str
    pattern: re.Pattern
    note: str


VERIFY_SPECS = (
    Verify("정부24 문서확인번호",
           re.compile(r"\b(\d{4}-\d{4}-\d{4}-\d{4})\b"),
           "정부24(gov.kr)에서 조회"),

    Verify("certpia 인터넷발급번호",
           re.compile(r"(?:Internet\s*no|인터넷\s*발급번호)[)\s:：]*([0-9]{12,20})",
                      re.IGNORECASE),
           "certpia.com 원본대조 메뉴에서 조회 (발급일로부터 90일 이내)"),

    Verify("문서번호",
           re.compile(r"제\s*([0-9]{4}-[0-9]{4,10})\s*호"),
           "발급기관 자체 문서번호 — 진위확인용이 아닐 수 있음"),
)
