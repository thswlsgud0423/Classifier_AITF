# ══════════════════════════════════════════════════════════════════════
#  [배경] 왜 자간(글자 사이 공백)을 신경써야 하는가
# ══════════════════════════════════════════════════════════════════════
#
# 증명서는 라벨을 양쪽 정렬하려고 글자 사이를 벌려 인쇄합니다.
#
#     성       명 : 김선홍
#     생 년 월 일 : 1998년 03월 17일
#
# 그래서 "성명" 을 그대로 찾으면 못 잡습니다.
# 아래 spaced() 가 글자 사이에 \s* 를 자동으로 끼워 넣어 해결합니다.
#
#     spaced("생년월일")  →  생\s*년\s*월\s*일
#
# 즉 여러분은 자간을 신경쓸 필요 없이 "생년월일" 이라고만 적으면 됩니다.

def spaced(label: str) -> str:
    return r"\s*".join(re.escape(c) for c in label)


# ══════════════════════════════════════════════════════════════════════
#  [배경] 값의 모양 (패턴)
# ══════════════════════════════════════════════════════════════════════
#
# 라벨 뒤에 오는 "값"이 어떻게 생겼는지 알려주는 부분입니다.
# 대부분 아래 4개 중 하나를 쓰시면 됩니다.

P_NAME = r"([가-힣]{2,6})"                       # 한글 이름
P_DATE = r"(\d{4}\s*[년./-]\s*\d{1,2}\s*[월./-]\s*\d{1,2}\s*일?)"  # 날짜(형식 무관)
P_TEXT = r"([^\n]{1,40}?)\s*$"                   # 그 줄의 나머지 전부
P_NUM = r"([0-9]{4,20})"                         # 숫자


@dataclass(frozen=True)
class Field:
    key: str            # 내부 이름 (영문, 바꾸지 마세요)
    display: str        # 화면에 보일 이름
    labels: tuple       # ★ 여기에 라벨 표현을 추가하시면 됩니다
    pattern: str        # 값의 모양 (위 P_ 중 하나)
    required: bool = False   # True 면 못 뽑았을 때 "실무자 입력 필요" 표시

    def regex(self):
        alts = "|".join(spaced(l) for l in self.labels)
        # re.MULTILINE 필수 — 없으면 $ 가 문서 전체의 끝만 뜻해서
        # 문서 중간 줄이 전부 매칭에 실패합니다.
        return re.compile(rf"(?:{alts})\s*[:：]\s*{self.pattern}", re.MULTILINE)


